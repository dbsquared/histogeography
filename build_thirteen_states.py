# 正向变换：(ref_px, ref_py) → (lon, lat)
def ref_to_lonlat(px, py):
    """参考图像素坐标 → WGS84 经纬度（仿射）"""
    lon = 0.00419271005911229 * px + (-7.233306857103161e-05) * py + 90.4140354255938
    lat = (-0.0002032903298687787) * px + (-0.0034568442670984915) * py + 45.09665432873004
    return round(lon, 5), round(lat, 5)


# 反向变换：WGS84 → 参考图像素（用于验证）
def lonlat_to_ref(lon, lat):
    px = 238.2674812564853 * lon + (-4.98565070576299) * lat + (-21317.888324609285)
    py = (-14.012050043055606) * lon + (-288.9879867981198) * lat + 14299.27733476843
    return round(px, 1), round(py, 1)


# ── 2. 工具函数 ──

def make_state_polygon(name, pinyin, capital, color, vertices, seats):
    """
    构建一个州的 Polygon Feature。
    vertices: [(lon, lat), ...] — 闭合多边形（首尾相同会自动处理）
    seats: [{name, name_modern, lon, lat, role}, ...] — 郡治/主要城池
    """
    # 确保闭合
    if vertices and vertices[0] != vertices[-1]:
        vertices = vertices + [vertices[0]]

    coords_2d = [[list(v) for v in vertices]]
    feature = {
        "type": "Feature",
        "properties": {
            "kind": "thirteen_states",
            "state_name": name,
            "pinyin": pinyin,
            "capital": capital,
            "fill_color": color,
            "era": "东汉永和五年(140)–建安二十五年(220)",
            "seat_count": len(seats),
        },
        "geometry": {
            "type": "Polygon",
            "coordinates": coords_2d
        }
    }
    return feature


def make_city_feature(ancient, modern, lon, lat, state_name, role="commandery_seat"):
    """构建古代城池 Point Feature"""
    return {
        "type": "Feature",
        "properties": {
            "kind": "ancient_city",
            "name_ancient": ancient,
            "name_modern": modern or "",
            "state": state_name,
            "role": role,  # capital | commandery_seat | major_city | fortress
        },
        "geometry": {
            "type": "Point",
            "coordinates": [round(lon, 5), round(lat, 5)]
        }
    }


