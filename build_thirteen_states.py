def build_geojson():
    """构建完整的 GeoJSON FeatureCollection"""
    features = []

    for sd in STATES_DATA:
        # 州面要素
        feat = make_state_polygon(
            name=sd["name"],
            pinyin=sd["pinyin"],
            capital=sd["seats"][0][0],  # 第一个seat是治所
            color=sd["color"],
            vertices=sd["vertices"],
            seats=sd["seats"],
        )
        features.append(feat)

        # 古代城池点要素
        for seat in sd["seats"]:
            city_feat = make_city_feature(
                ancient=seat[0],
                modern=seat[1],
                lon=seat[2],
                lat=seat[3],
                state_name=sd["name"],
                role=seat[4],
            )
            features.append(city_feat)

    geojson = {
        "type": "FeatureCollection",
        "metadata": {
            "title": "汉末十三州版图",
            "era": "东汉永和五年(公元140年) – 建安二十五年(公元220年)",
            "source_ref": "bilibili widezhang / 谭其骧《中国历史地图集·东汉》",
            "source_base": "SRTM 90m DEM (地理空间数据云 www.gscloud.cn)",
            "method": "参考图像素→仿射变换→WGS84经纬度，人工数字化州界折点",
            "calibration": "13-GCP affine (全览-郡治.png 9933×7015)",
            "states_count": 13,
            "total_cities": sum(len(sd["seats"]) for sd in STATES_DATA),
        },
        "features": features,
    }

    return geojson


