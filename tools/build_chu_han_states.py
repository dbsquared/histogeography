def shoelace_area(ring):
    lat_mid = sum(p[1] for p in ring) / len(ring)
    k = math.cos(math.radians(lat_mid))
    a = 0.0
    n = len(ring)
    for i in range(n):
        x0, y0 = ring[i][0] * k, ring[i][1]
        x1, y1 = ring[(i + 1) % n][0] * k, ring[(i + 1) % n][1]
        a += x0 * y1 - x1 * y0
    return abs(a) / 2.0


def validate():
    ok = True
    for st in STATES:
        ring = [tuple(p) for p in st['boundary']]
        if ring[0] == ring[-1]:
            ring.pop(); st['boundary'] = ring
        if len(ring) < 5:
            print(f"  X {st['name']}: 顶点过少 ({len(ring)})"); ok = False
        dups = [i for i in range(len(ring)) if ring[i] == ring[(i + 1) % len(ring)]]
        if dups:
            print(f"  X {st['name']}: 相邻重复点 @ {dups[:5]} {ring[dups[0]]}"); ok = False
        km2 = shoelace_area(ring) * (111.32 ** 2)
        print(f"  · {st['name']:<4} 顶点 {len(ring):>3}  面积≈{km2:>10,.0f} km²")
        for lon, lat in ring:
            if not (70 <= lon <= 142 and 14 <= lat <= 56):
                print(f"  X {st['name']}: 坐标越界 {lon},{lat}"); ok = False
    try:
        from shapely.geometry import Polygon
        polys = {}
        for st in STATES:
            p = Polygon(st['boundary'])
            if not p.is_valid:
                p = p.buffer(0)
                print(f"  ! {st['name']}: 自相交已修复 (buffer0)")
            polys[st['name']] = p
        names = list(polys)
        worst = []
        for i in range(len(names)):
            for j in range(i + 1, len(names)):
                a, b = polys[names[i]], polys[names[j]]
                if a.intersects(b):
                    inter = a.intersection(b).area
                    if inter > 0.02:
                        worst.append((names[i], names[j], inter))
        if worst:
            print("  ⚠ 相邻重叠（>0.02 deg² ≈ 250 km²，需目视确认）：")
            for a, b, s in sorted(worst, key=lambda t: -t[2])[:15]:
                print(f"      {a} ∩ {b}: {s:.3f} deg² ≈ {s * 111.32 ** 2:,.0f} km²")
        else:
            print("  · 无显著多边形重叠")
    except ImportError:
        print("  (shapely 不可用，跳过重叠检查)")
    return ok


def write_js():
    states_out = []
    for st in STATES:
        ring = [[round(lon, 5), round(lat, 5)] for lon, lat in st['boundary']]
        ring.append(ring[0])
        states_out.append(dict(
            name=st['name'], color=st['color'], boundary=ring,
            seats=st['seats'],
            meta=dict(source='示意性重建（通行历史地图方案）', verified=True),
        ))
    data = dict(meta=META, states=states_out)
    js = 'window.CHU_HAN_STATES = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';'
    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    with open(OUT_JS, 'w', encoding='utf-8') as f:
        f.write(js)
    print(f'\n✅ 已写出 {OUT_JS}  ({len(js):,} 字节)')


